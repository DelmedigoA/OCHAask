create table if not exists public.bearing_witness_document_pages (
    id bigint generated by default as identity primary key,
    document_id text not null,
    document_version text not null,
    page integer not null check (page > 0),
    title text not null,
    source_url text not null,
    content text not null,
    embedding extensions.vector(1536) not null,
    embedding_model text not null,
    content_search tsvector generated always as (to_tsvector('english'::regconfig, content)) stored,
    created_at timestamptz not null default now(),
    unique (document_id, page, embedding_model)
);

create index if not exists bearing_witness_document_pages_embedding_idx
    on public.bearing_witness_document_pages
    using hnsw (embedding extensions.vector_cosine_ops);
create index if not exists bearing_witness_document_pages_content_idx
    on public.bearing_witness_document_pages using gin (content_search);
create index if not exists bearing_witness_document_pages_document_idx
    on public.bearing_witness_document_pages (document_id, embedding_model, page);

alter table public.bearing_witness_document_pages enable row level security;
revoke all on public.bearing_witness_document_pages from public, anon, authenticated;
grant select, insert, delete on public.bearing_witness_document_pages to service_role;
grant usage, select on sequence public.bearing_witness_document_pages_id_seq to service_role;

create or replace function public.replace_bearing_witness_document_pages(
    target_document_id text,
    target_version text,
    target_title text,
    target_source_url text,
    pages_data jsonb,
    model_name text
)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
begin
    if nullif(trim(target_document_id), '') is null
       or nullif(trim(target_version), '') is null
       or nullif(trim(target_title), '') is null
       or nullif(trim(target_source_url), '') is null
       or nullif(trim(model_name), '') is null
       or jsonb_typeof(pages_data) <> 'array'
       or jsonb_array_length(pages_data) = 0 then
        raise exception 'Document identity, source, model, and non-empty pages are required';
    end if;

    perform pg_catalog.pg_advisory_xact_lock(
        pg_catalog.hashtextextended(target_document_id || ':' || model_name, 0)
    );

    delete from public.bearing_witness_document_pages
    where document_id = target_document_id and embedding_model = model_name;

    insert into public.bearing_witness_document_pages (
        document_id, document_version, page, title, source_url, content, embedding, embedding_model
    )
    select
        target_document_id,
        target_version,
        (page_data->>'page')::integer,
        target_title,
        target_source_url,
        page_data->>'content',
        (page_data->>'embedding')::extensions.vector(1536),
        model_name
    from jsonb_array_elements(pages_data) as pages(page_data);
end;
$$;

revoke all on function public.replace_bearing_witness_document_pages(text, text, text, text, jsonb, text)
    from public, anon, authenticated;
grant execute on function public.replace_bearing_witness_document_pages(text, text, text, text, jsonb, text)
    to service_role;

create or replace function public.read_bearing_witness_document_pages(
    target_document_id text,
    target_model text,
    start_page integer,
    end_page integer
)
returns table (
    document_id text,
    document_version text,
    title text,
    source_url text,
    page integer,
    content text
)
language sql
stable
security invoker
set search_path = ''
as $$
    select p.document_id, p.document_version, p.title, p.source_url, p.page, p.content
    from public.bearing_witness_document_pages p
    where p.document_id = target_document_id
      and p.embedding_model = target_model
      and p.page between start_page and end_page
      and start_page > 0
      and end_page >= start_page
      and end_page - start_page <= 9
    order by p.page
    limit 10;
$$;

revoke all on function public.read_bearing_witness_document_pages(text, text, integer, integer)
    from public, anon, authenticated;
grant execute on function public.read_bearing_witness_document_pages(text, text, integer, integer)
    to service_role;

create or replace function public.hybrid_search_bearing_witness_document(
    query_text text,
    query_embedding extensions.vector(1536),
    model_name text,
    match_count integer default 5,
    semantic_weight double precision default 1,
    keyword_weight double precision default 1
)
returns table (
    document_id text,
    document_version text,
    title text,
    source_url text,
    page integer,
    content text,
    fusion_score double precision
)
language sql
stable
security invoker
set search_path = ''
as $$
    with semantic_candidates as materialized (
        select p.id, p.embedding operator(extensions.<=>) query_embedding as distance
        from public.bearing_witness_document_pages p
        where p.document_id = 'bearing-witness-gaza-english'
          and p.embedding_model = model_name
          and semantic_weight > 0
        order by p.embedding operator(extensions.<=>) query_embedding
        limit least(greatest(match_count, 1), 20) * 10
    ), semantic as (
        select id, row_number() over (order by distance, id) as rank
        from semantic_candidates
    ), keywords as (
        select p.id,
            row_number() over (
                order by ts_rank_cd(
                    p.content_search,
                    websearch_to_tsquery('english'::regconfig, query_text)
                ) desc,
                p.id
            ) as rank
        from public.bearing_witness_document_pages p
        where p.document_id = 'bearing-witness-gaza-english'
          and p.embedding_model = model_name
          and keyword_weight > 0
          and p.content_search @@ websearch_to_tsquery('english'::regconfig, query_text)
        order by ts_rank_cd(
            p.content_search,
            websearch_to_tsquery('english'::regconfig, query_text)
        ) desc, p.id
        limit least(greatest(match_count, 1), 20) * 10
    ), fused as (
        select coalesce(s.id, k.id) as id,
            coalesce(semantic_weight / (60.0 + s.rank), 0)
            + coalesce(keyword_weight / (60.0 + k.rank), 0) as score
        from semantic s
        full outer join keywords k on s.id = k.id
    )
    select p.document_id, p.document_version, p.title, p.source_url,
        p.page, p.content, f.score
    from fused f
    join public.bearing_witness_document_pages p on p.id = f.id
    order by f.score desc, p.page
    limit least(greatest(match_count, 1), 20);
$$;

revoke all on function public.hybrid_search_bearing_witness_document(text, extensions.vector, text, integer, double precision, double precision)
    from public, anon, authenticated;
grant execute on function public.hybrid_search_bearing_witness_document(text, extensions.vector, text, integer, double precision, double precision)
    to service_role;
