create schema if not exists extensions;
create extension if not exists vector with schema extensions;

create table if not exists public.report_embeddings (
    id bigint generated by default as identity primary key,
    report_id uuid not null references public.report_landings(id) on delete cascade,
    chunk_index integer not null default 0,
    content text not null,
    embedding extensions.vector(1536),
    embedding_model text not null default 'text-embedding-3-small',
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (report_id, embedding_model, chunk_index)
);

create index if not exists report_embeddings_embedding_hnsw_idx
    on public.report_embeddings
    using hnsw (embedding extensions.vector_cosine_ops);

create index if not exists report_embeddings_report_id_idx
    on public.report_embeddings (report_id);

alter table public.report_embeddings enable row level security;
revoke all on public.report_embeddings from anon, authenticated;
grant all on public.report_embeddings to service_role;
grant usage, select on sequence public.report_embeddings_id_seq to service_role;

create or replace function public.match_report_embeddings(
    query_embedding extensions.vector(1536),
    match_count integer default 10,
    filter jsonb default '{}'::jsonb
)
returns table (
    id bigint,
    report_id uuid,
    chunk_index integer,
    content text,
    landing_url text,
    title text,
    metadata jsonb,
    similarity double precision
)
language sql
stable
set search_path = ''
as $$
    select
        e.id,
        e.report_id,
        e.chunk_index,
        e.content,
        r.landing_url,
        r.title,
        e.metadata,
        1 - (e.embedding operator(extensions.<=>) query_embedding) as similarity
    from public.report_embeddings as e
    join public.report_landings as r on r.id = e.report_id
    where e.embedding is not null
      and e.metadata @> filter
    order by e.embedding operator(extensions.<=>) query_embedding
    limit least(greatest(match_count, 1), 100);
$$;

revoke all on function public.match_report_embeddings(extensions.vector, integer, jsonb) from public, anon, authenticated;
grant execute on function public.match_report_embeddings(extensions.vector, integer, jsonb) to service_role;
