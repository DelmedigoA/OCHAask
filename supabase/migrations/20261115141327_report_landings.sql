create table if not exists public.report_landings (
    id uuid primary key,
    landing_url text not null unique,
    title text not null,
    report_type text,
    posted date,
    originally_published date,
    origin_url text,
    main_image_url text,
    main_image_credit text,
    key_points text[] not null default '{}',
    metadata jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.report_attachments (
    id bigint generated by default as identity primary key,
    report_id uuid not null references public.report_landings(id) on delete cascade,
    filename text not null,
    url text not null,
    description text,
    file_type text,
    size text,
    language text,
    preview_url text,
    created_at timestamptz not null default now(),
    unique (report_id, url)
);

create index if not exists report_landings_posted_idx on public.report_landings (posted desc);
create index if not exists report_attachments_report_id_idx on public.report_attachments (report_id);
create index if not exists report_attachments_language_idx on public.report_attachments (language);

alter table public.report_landings enable row level security;
alter table public.report_attachments enable row level security;
